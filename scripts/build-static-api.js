const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '..');
const postsFile = path.join(rootDir, 'posts.json');
const apiDir = path.join(rootDir, 'api', 'posts');
const buildIdFile = path.join(rootDir, 'assets', 'js', 'build-id.js');

// Ensure api directories exist
if (!fs.existsSync(path.join(rootDir, 'api'))) {
    fs.mkdirSync(path.join(rootDir, 'api'));
}
if (!fs.existsSync(apiDir)) {
    fs.mkdirSync(apiDir);
}

try {
    const rawData = fs.readFileSync(postsFile, 'utf8');
    const data = JSON.parse(rawData);
    const posts = data.posts || [];

    // Content hash used as a cache-bust token on API fetches in the SPA.
    const buildId = crypto.createHash('sha256').update(rawData).digest('hex').slice(0, 12);

    // Create index.json with metadata only
    const indexPosts = posts.map(post => {
        return {
            title: post.title,
            slug: post.slug,
            publishedAt: post.publishedAt,
            summary: post.summary,
            tags: post.tags,
            source: post.source,
            contributor: post.contributor
        };
    });

    fs.writeFileSync(
        path.join(rootDir, 'api', 'index.json'),
        JSON.stringify({ posts: indexPosts })
    );

    console.log(`Generated api/index.json with ${indexPosts.length} posts metadata.`);

    // Create individual post JSON files
    let createdCount = 0;
    posts.forEach(post => {
        if (post.slug) {
            const postFilePath = path.join(apiDir, `${post.slug}.json`);
            fs.writeFileSync(postFilePath, JSON.stringify(post));
            createdCount++;
        }
    });

    console.log(`Generated ${createdCount} individual post files in api/posts/`);

    // Emit BUILD_ID for client-side cache busting of API JSON.
    const jsDir = path.dirname(buildIdFile);
    if (!fs.existsSync(jsDir)) {
        fs.mkdirSync(jsDir, { recursive: true });
    }
    fs.writeFileSync(
        buildIdFile,
        [
            '// Auto-generated by scripts/build-static-api.js — do not edit by hand.',
            `export const BUILD_ID = ${JSON.stringify(buildId)};`,
            '',
        ].join('\n'),
        'utf8'
    );
    console.log(`Wrote assets/js/build-id.js (BUILD_ID=${buildId}).`);

} catch (err) {
    console.error('Error building static API:', err);
    process.exit(1);
}
